import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { ENGINE } from "@answer-checker/core";
import { loadBench } from "./load";
import { runBench, summarize, type Row, type Summary } from "./score";

const dir = resolve(process.argv[2] ?? "../../bench/de-arbeitsrecht");
const cases = loadBench(dir);
const rows = runBench(cases);
const summary = summarize(rows);

function pct(n: number, d: number): string {
  return d ? `${Math.round((n / d) * 100)}%` : "n/a";
}

function report(s: Summary, all: Row[]): string {
  const lines = [
    `# Results: ${s.cases} questions, ${s.cases * 3} answers`,
    "",
    `Engine ${ENGINE.name} ${ENGINE.version}. Generated by \`npm run bench --workspace @answer-checker/bench\`.`,
    "",
    "| Measure | Result |",
    "| --- | --- |",
    `| Wrong answers caught | ${s.drifted.caught} of ${s.drifted.total} (${pct(s.drifted.caught, s.drifted.total)}) |`,
    `| ...by the check meant to catch them | ${s.drifted.caughtByIntended} of ${s.drifted.total} (${pct(s.drifted.caughtByIntended, s.drifted.total)}) |`,
    `| Faithful answers passed | ${s.faithful.passed} of ${s.faithful.total} (${pct(s.faithful.passed, s.faithful.total)}) |`,
    `| Correct paraphrases passed | ${s.paraphrase.passed} of ${s.paraphrase.total} (${pct(s.paraphrase.passed, s.paraphrase.total)}) |`,
    `| A "fail" verdict was right | ${pct(Math.round(s.failPrecision * 1000), 1000)} |`,
    "",
    "## Wrong answers caught, by kind of mistake",
    "",
    "| Mistake | Caught |",
    "| --- | --- |",
    ...Object.entries(s.byDrift).map(([id, v]) => `| ${id} | ${v.caught} of ${v.total} |`),
    "",
    "## False alarms on correct answers, by check",
    "",
    "| Check | Correct answers it failed |",
    "| --- | --- |",
    ...Object.entries(s.falseAlarms).map(([id, n]) => `| ${id} | ${n} |`),
    "",
    "## Misses and false alarms",
    "",
    "| Case | Answer | Verdict | Failed checks |",
    "| --- | --- | --- | --- |",
    ...all
      .filter((r) => (r.kind === "drifted") === (r.verdict === "pass"))
      .map((r) => `| ${r.id} | ${r.kind} | ${r.verdict} | ${r.failed.join(", ") || "none"} |`),
  ];
  return lines.join("\n") + "\n";
}

mkdirSync(join(dir, "results"), { recursive: true });
writeFileSync(join(dir, "results", "latest.json"), JSON.stringify({ engine: ENGINE, summary, rows }, null, 2) + "\n");
writeFileSync(join(dir, "results", "RESULTS.md"), report(summary, rows));
console.log(report(summary, rows).split("\n").slice(0, 12).join("\n"));
