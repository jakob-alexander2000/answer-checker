import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { ENGINE } from "@answer-checker/core";
import { loadBench } from "./load";
import { runBench, summarize, type Row, type Summary } from "./score";

const args = process.argv.slice(2);
const asBaseline = args.includes("--baseline");
const dir = resolve(args.find((a) => !a.startsWith("--")) ?? "../../bench/de-arbeitsrecht");
const cases = loadBench(dir);
const rows = runBench(cases);
const summaries = {
  all: summarize(rows),
  dev: summarize(rows.filter((r) => r.split === "dev")),
  holdout: summarize(rows.filter((r) => r.split === "holdout")),
};
type Summaries = typeof summaries;
type Saved = { engine: typeof ENGINE; summary: Summaries };

function pct(n: number, d: number): string {
  return d ? `${Math.round((n / d) * 100)}%` : "n/a";
}

function frac(n: number, d: number): string {
  return `${n} of ${d} (${pct(n, d)})`;
}

const MEASURES: [string, (s: Summary) => string][] = [
  ["Wrong answers caught", (s) => frac(s.drifted.caught, s.drifted.total)],
  ["...by the check meant to catch them", (s) => frac(s.drifted.caughtByIntended, s.drifted.total)],
  ["Faithful answers passed", (s) => frac(s.faithful.passed, s.faithful.total)],
  ["Correct paraphrases passed", (s) => frac(s.paraphrase.passed, s.paraphrase.total)],
  ['A "fail" verdict was right', (s) => pct(Math.round(s.failPrecision * 1000), 1000)],
];

function report(now: Summaries, all: Row[], before: Saved | null): string {
  const s = now.all;
  const head = before
    ? [`| Measure | Held-out (${now.holdout.cases}) | Dev (${now.dev.cases}) | All | All, engine ${before.engine.version} |`, "| --- | --- | --- | --- | --- |"]
    : [`| Measure | Held-out (${now.holdout.cases}) | Dev (${now.dev.cases}) | All |`, "| --- | --- | --- | --- |"];
  const lines = [
    `# Results: ${s.cases} questions, ${s.cases * 3} answers`,
    "",
    `Engine ${ENGINE.name} ${ENGINE.version}. Generated by \`npm run bench\`.`,
    "",
    "The engine was tuned on the dev questions only. The held-out questions were written before tuning and never looked at during it, so they are the fairer number.",
    "",
    ...head,
    ...MEASURES.map(([label, fn]) =>
      `| ${label} | ${fn(now.holdout)} | ${fn(now.dev)} | ${fn(s)} |${before ? ` ${fn(before.summary.all)} |` : ""}`,
    ),
    "",
    "## Wrong answers caught, by kind of mistake",
    "",
    "| Mistake | Caught |",
    "| --- | --- |",
    ...Object.entries(s.byDrift).map(([id, v]) => `| ${id} | ${v.caught} of ${v.total} |`),
    "",
    "## False alarms on correct answers, by check",
    "",
    "| Check | Correct answers it failed |",
    "| --- | --- |",
    ...Object.entries(s.falseAlarms).map(([id, n]) => `| ${id} | ${n} |`),
    "",
    "## Misses and false alarms",
    "",
    "| Case | Split | Answer | Verdict | Failed checks |",
    "| --- | --- | --- | --- | --- |",
    ...all
      .filter((r) => (r.kind === "drifted") === (r.verdict === "pass"))
      .map((r) => `| ${r.id} | ${r.split} | ${r.kind} | ${r.verdict} | ${r.failed.join(", ") || "none"} |`),
  ];
  return lines.join("\n") + "\n";
}

const out = join(dir, "results");
mkdirSync(out, { recursive: true });
const baselineFile = join(out, "baseline.json");
if (asBaseline) {
  writeFileSync(baselineFile, JSON.stringify({ engine: ENGINE, summary: summaries }, null, 2) + "\n");
  console.log(`Baseline written for engine ${ENGINE.version}.`);
} else {
  const before = existsSync(baselineFile) ? (JSON.parse(readFileSync(baselineFile, "utf8")) as Saved) : null;
  const text = report(summaries, rows, before);
  writeFileSync(join(out, "latest.json"), JSON.stringify({ engine: ENGINE, summary: summaries, rows }, null, 2) + "\n");
  writeFileSync(join(out, "RESULTS.md"), text);
  console.log(text.split("\n").slice(0, 14).join("\n"));
}
